/**
 * Hyphens rather than spaces.
 *
 * A generated passphrase is copied, not typed, and it travels through chat
 * windows and mail clients on the way to the person it is for. Those collapse
 * runs of whitespace and trim the ends; a hyphen arrives as it left.
 */
export const SUGGESTION_SEPARATOR = '-'

export function suggestPassphrase(words = WORDS_PER_SUGGESTION): string {
  // One byte per word, and the list holds exactly 256: the byte *is* the index.
  return [...randomBytes(words)].map((byte) => WORDS[byte] as string).join(SUGGESTION_SEPARATOR)
}
