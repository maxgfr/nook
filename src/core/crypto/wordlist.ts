/**
 * Suggesting a passphrase somebody can actually keep.
 *
 * `checkPassphrase` rejects short ones, which is a floor and not much help:
 * people asked for a long secret reach for a sentence they already use
 * somewhere else. This offers one instead, drawn from real randomness.
 *
 * Words rather than characters, for the reason `kdf.ts` gives: composition
 * rules push people towards `Password1!`, and a string of symbols gets written
 * on paper or lost. Six words are far stronger than either and can be read
 * aloud down a phone.
 *
 * **Exactly 256 words, and that is not decoration.** One random byte selects
 * one word with no arithmetic at all, so there is no modulo and therefore no
 * bias: every word is exactly as likely as every other. Any other list size
 * would need rejection sampling to say the same, and the version of this that
 * forgets to do it is indistinguishable from the version that does.
 *
 * Eight bits a word, six words: 48 bits of entropy, every bit of it from
 * `crypto.getRandomValues`. Against Argon2id at the settings in `kdf.ts` that
 * is not brute-forceable by anyone.
 */

